-- Customers a car belongs to (same rule as portal_vehicle_ids). Server only.
create or replace function public.vehicle_customer_ids(p_vehicle_id uuid)
returns setof uuid
language sql stable security definer set search_path = public
as $$
  select i.customer_id
    from public.invoice_items it
    join public.invoices i on i.id = it.invoice_id
   where it.vehicle_id = p_vehicle_id
     and i.customer_id is not null
     and i.status not in ('draft', 'cancelled')
     and i.doc_type in ('invoice', 'auction_deposit')
  union
  select r.customer_id
    from public.reservations r
   where r.vehicle_id = p_vehicle_id
     and r.customer_id is not null
     and r.status in ('active', 'invoiced')
$$;
revoke all on function public.vehicle_customer_ids(uuid) from public, anon, authenticated;
grant execute on function public.vehicle_customer_ids(uuid) to service_role;
