-- =====================================================================
-- 0042: phone push notifications (Web Push) for the website / app
--
--  * One row per browser/phone that allowed notifications. `topics` is what
--    it wants: 'stock' (new cars), 'offers' (new deals), 'account' (invoices,
--    payments and other alerts for the signed-in customer).
--  * user_id is whoever was signed in when the phone last checked in, so a
--    shared phone stops getting someone's account alerts after they sign out.
--  * Visitors never read or write the table directly: they save and remove
--    their own row through the two RPCs below (the endpoint is the secret).
--    The server sends with the service key (src/lib/notify.ts).
-- Safe to re-run.
-- =====================================================================

create table if not exists public.push_subscriptions (
  id          bigint generated by default as identity primary key,
  endpoint    text not null unique,
  p256dh      text not null,
  auth        text not null,
  user_id     uuid references auth.users (id) on delete set null,
  topics      text[] not null default '{stock,offers,account}',
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

do $$ begin
  alter table public.push_subscriptions add constraint push_subscriptions_values_chk check (
    endpoint like 'https://%' and char_length(endpoint) <= 1000
    and char_length(p256dh) between 80 and 100
    and char_length(auth) between 16 and 30
    and topics <@ array['stock','offers','account']::text[]);
exception when duplicate_object then null; end $$;

create index if not exists push_subscriptions_user_idx   on public.push_subscriptions (user_id) where user_id is not null;
create index if not exists push_subscriptions_topics_idx on public.push_subscriptions using gin (topics);

alter table public.push_subscriptions enable row level security;
-- No policies: only the RPCs below and the service key touch it.

-- Save (or refresh) this phone's subscription, tied to the current sign-in (none for visitors).
create or replace function public.save_push_subscription(p_endpoint text, p_p256dh text, p_auth text, p_topics text[])
returns void
language sql security definer set search_path = public
as $$
  insert into public.push_subscriptions (endpoint, p256dh, auth, user_id, topics)
  values (p_endpoint, p_p256dh, p_auth, auth.uid(), coalesce(p_topics, '{}'))
  on conflict (endpoint) do update
     set p256dh = excluded.p256dh, auth = excluded.auth, user_id = excluded.user_id,
         topics = excluded.topics, updated_at = now()
$$;
revoke all on function public.save_push_subscription(text, text, text, text[]) from public;
grant execute on function public.save_push_subscription(text, text, text, text[]) to anon, authenticated;

create or replace function public.delete_push_subscription(p_endpoint text)
returns void
language sql security definer set search_path = public
as $$
  delete from public.push_subscriptions where endpoint = p_endpoint
$$;
revoke all on function public.delete_push_subscription(text) from public;
grant execute on function public.delete_push_subscription(text) to anon, authenticated;

