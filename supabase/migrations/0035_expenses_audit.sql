-- =====================================================================
-- 0035: expense book, commission paid per car, audit trail (business ledger)
--
--  * company_expenses: overheads and other costs (rent, salaries,
--    shipping, utilities, marketing, bank charges...), optionally linked to
--    a car. Amount in any currency with its rate to JPY (1 unit = N JPY);
--    amount_jpy is computed. Admins see all; a manager sees their office
--    (or all when they have no office). Sales agents have no access (cost
--    data). Receipts go to the private 'expense-receipts' bucket, uploaded
--    and signed only by the server (service key).
--  * Commission paid: an admin marks a car's commission paid (agent,
--    amount, date); that also books it in the expense book. Reverse undoes
--    both, for a car marked by mistake.
--  * audit_log: who created, changed or deleted what, and when, for every
--    table that moves money or stock. Updates store only the changed
--    columns (old and new). Written by triggers; admins read it; nobody can
--    edit or delete it through the API.
-- Safe to re-run.
-- =====================================================================

-- ---------------------------------------------------------------------
-- Expense book
-- ---------------------------------------------------------------------
create table if not exists public.company_expenses (
  id              bigint generated by default as identity primary key,
  expense_date    date not null default current_date,
  category        text not null,
  description     text not null,
  paid_to         text,
  reference       text,
  payment_method  text,
  currency        text not null default 'JPY',
  amount          numeric(14, 2) not null,
  fx_rate         numeric(14, 6) not null default 1,   -- 1 unit of currency = N JPY
  amount_jpy      numeric(16, 0) generated always as (round(amount * fx_rate)) stored,
  vehicle_id      uuid references public.vehicles (id) on delete set null,
  office          text,
  receipt_path    text,
  receipt_name    text,
  receipt_type    text,
  created_by      uuid references public.profiles (id) on delete set null default auth.uid(),
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now()
);

do $$ begin
  alter table public.company_expenses add constraint company_expenses_values_chk check (
    currency in ('JPY', 'USD', 'EUR', 'GBP', 'SGD', 'TWD', 'THB')
    and amount > 0 and fx_rate > 0
    and char_length(category) between 1 and 40
    and char_length(description) between 1 and 300
    and char_length(coalesce(paid_to, '')) <= 120
    and char_length(coalesce(reference, '')) <= 120
    and char_length(coalesce(payment_method, '')) <= 40
    and (receipt_path is null or (receipt_type in ('image/jpeg', 'image/png', 'image/webp', 'application/pdf')
                                  and char_length(coalesce(receipt_name, '')) between 1 and 200)));
exception when duplicate_object then null; end $$;

create index if not exists company_expenses_date_idx     on public.company_expenses (expense_date desc);
create index if not exists company_expenses_category_idx on public.company_expenses (category, expense_date desc);
create index if not exists company_expenses_vehicle_idx  on public.company_expenses (vehicle_id);
create index if not exists company_expenses_creator_idx  on public.company_expenses (created_by);

-- Admin: everything. Manager: their office (or everything when they have no office).
create or replace function public.can_manage_expense(p_office text)
returns boolean
language sql stable security definer set search_path = public
as $$
  select public.is_staff(array['admin']::public.user_role[])
      or (public.is_staff(array['manager']::public.user_role[])
          and (public.auth_office() is null or p_office is null or p_office = public.auth_office()))
$$;
revoke all on function public.can_manage_expense(text) from public, anon;
grant execute on function public.can_manage_expense(text) to authenticated;

alter table public.company_expenses enable row level security;
drop policy if exists company_expenses_read on public.company_expenses;
create policy company_expenses_read on public.company_expenses for select to authenticated
  using ((select public.can_manage_expense(office)));
drop policy if exists company_expenses_insert on public.company_expenses;
create policy company_expenses_insert on public.company_expenses for insert to authenticated
  with check ((select public.can_manage_expense(office)));
drop policy if exists company_expenses_update on public.company_expenses;
create policy company_expenses_update on public.company_expenses for update to authenticated
  using ((select public.can_manage_expense(office))) with check ((select public.can_manage_expense(office)));
drop policy if exists company_expenses_delete on public.company_expenses;
create policy company_expenses_delete on public.company_expenses for delete to authenticated
  using ((select public.can_manage_expense(office)));

drop trigger if exists company_expenses_touch on public.company_expenses;
create trigger company_expenses_touch before update on public.company_expenses
  for each row execute function public.touch_updated_at();

