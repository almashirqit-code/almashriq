-- ---------------------------------------------------------------------
-- Commission paid (per car). Marking it records the commission as an
-- expense (category 'salaries'); reversing removes that expense again.
-- Admin only. Both steps are in the audit trail.
-- ---------------------------------------------------------------------
alter table public.vehicles
  add column if not exists commission_paid_at     date,
  add column if not exists commission_agent_id    uuid references public.profiles (id) on delete set null,
  add column if not exists commission_amount      numeric(14, 2),
  add column if not exists commission_currency    text,
  add column if not exists commission_note        text,
  add column if not exists commission_expense_id  bigint references public.company_expenses (id) on delete set null,
  add column if not exists commission_marked_by   uuid references public.profiles (id) on delete set null;
create index if not exists vehicles_commission_agent_idx   on public.vehicles (commission_agent_id);
create index if not exists vehicles_commission_expense_idx on public.vehicles (commission_expense_id);
create index if not exists vehicles_commission_marker_idx  on public.vehicles (commission_marked_by);

create or replace function public.mark_commission_paid(
  p_vehicle uuid, p_agent uuid, p_amount numeric, p_currency text, p_fx_rate numeric, p_paid_on date, p_note text default null)
returns void
language plpgsql security definer set search_path = public
as $$
declare
  v   public.vehicles;
  who text;
  eid bigint;
begin
  if not public.is_staff(array['admin']::public.user_role[]) then raise exception 'not authorized'; end if;
  select * into v from public.vehicles where id = p_vehicle for update;
  if not found then raise exception 'Vehicle not found'; end if;
  if v.commission_paid_at is not null then raise exception 'Commission is already marked paid for this car'; end if;
  if p_amount is null or p_amount <= 0 then raise exception 'Enter the commission amount'; end if;
  if p_currency not in ('JPY', 'USD', 'EUR', 'GBP', 'SGD', 'TWD', 'THB') then raise exception 'Invalid currency'; end if;
  select coalesce(nullif(full_name, ''), email) into who from public.profiles where id = p_agent and active;
  if who is null then raise exception 'Choose the agent'; end if;

  insert into public.company_expenses (expense_date, category, description, paid_to, currency, amount, fx_rate, vehicle_id, payment_method)
  values (coalesce(p_paid_on, current_date), 'salaries', left('Commission · ' || v.stock_no || ' ' || v.make || ' ' || v.model, 300),
          left(who, 120), p_currency, round(p_amount, 2), coalesce(nullif(p_fx_rate, 0), 1), v.id, null)
  returning id into eid;

  update public.vehicles
     set commission_paid_at = coalesce(p_paid_on, current_date), commission_agent_id = p_agent,
         commission_amount = round(p_amount, 2), commission_currency = p_currency,
         commission_note = left(nullif(trim(coalesce(p_note, '')), ''), 300),
         commission_expense_id = eid, commission_marked_by = auth.uid()
   where id = v.id;
end $$;

create or replace function public.reverse_commission(p_vehicle uuid)
returns void
language plpgsql security definer set search_path = public
as $$
declare
  eid bigint;
begin
  if not public.is_staff(array['admin']::public.user_role[]) then raise exception 'not authorized'; end if;
  select commission_expense_id into eid from public.vehicles where id = p_vehicle for update;
  if not found then raise exception 'Vehicle not found'; end if;
  update public.vehicles
     set commission_paid_at = null, commission_agent_id = null, commission_amount = null, commission_currency = null,
         commission_note = null, commission_expense_id = null, commission_marked_by = null
   where id = p_vehicle;
  if eid is not null then delete from public.company_expenses where id = eid; end if;
end $$;

revoke all on function public.mark_commission_paid(uuid, uuid, numeric, text, numeric, date, text) from public, anon;
grant execute on function public.mark_commission_paid(uuid, uuid, numeric, text, numeric, date, text) to authenticated;
revoke all on function public.reverse_commission(uuid) from public, anon;
grant execute on function public.reverse_commission(uuid) to authenticated;

-- ---------------------------------------------------------------------
-- Audit trail
-- ---------------------------------------------------------------------
create table if not exists public.audit_log (
  id          bigint generated always as identity primary key,
  table_name  text not null,
  row_id      text,
  action      text not null check (action in ('insert', 'update', 'delete')),
  changed_by  uuid references auth.users (id) on delete set null,
  changed_at  timestamptz not null default now(),
  old_data    jsonb,
  new_data    jsonb
);
create index if not exists audit_log_row_idx  on public.audit_log (table_name, row_id, changed_at desc);
create index if not exists audit_log_time_idx on public.audit_log (changed_at desc);
create index if not exists audit_log_user_idx on public.audit_log (changed_by, changed_at desc);

alter table public.audit_log enable row level security;
drop policy if exists audit_log_admin on public.audit_log;
create policy audit_log_admin on public.audit_log for select to authenticated
  using ((select public.is_staff(array['admin']::public.user_role[])));

create or replace function public.trg_audit()
returns trigger
language plpgsql security definer set search_path = public
as $$
declare
  o jsonb;
  n jsonb;
  d_old jsonb := '{}'::jsonb;
  d_new jsonb := '{}'::jsonb;
  k text;
begin
  if tg_op = 'INSERT' then
    n := to_jsonb(new);
    insert into public.audit_log (table_name, row_id, action, changed_by, new_data)
    values (tg_table_name, n ->> 'id', 'insert', auth.uid(), n);
    return new;
  elsif tg_op = 'DELETE' then
    o := to_jsonb(old);
    insert into public.audit_log (table_name, row_id, action, changed_by, old_data)
    values (tg_table_name, o ->> 'id', 'delete', auth.uid(), o);
    return old;
  end if;

  o := to_jsonb(old);
  n := to_jsonb(new);
  for k in select jsonb_object_keys(n) loop
    if k <> 'updated_at' and (o -> k) is distinct from (n -> k) then
      d_old := d_old || jsonb_build_object(k, o -> k);
      d_new := d_new || jsonb_build_object(k, n -> k);
    end if;
  end loop;
  if d_new <> '{}'::jsonb then
    insert into public.audit_log (table_name, row_id, action, changed_by, old_data, new_data)
    values (tg_table_name, n ->> 'id', 'update', auth.uid(), d_old, d_new);
  end if;
  return new;
end $$;
revoke execute on function public.trg_audit() from public, anon, authenticated;

do $$
declare t text;
begin
  foreach t in array array[
    'invoices', 'invoice_items', 'payments', 'remittances', 'remittance_allocations',
    'reservations', 'vehicles', 'customers', 'payment_slips', 'company_expenses'
  ] loop
    execute format('drop trigger if exists %I on public.%I', t || '_audit', t);
    execute format('create trigger %I after insert or update or delete on public.%I for each row execute function public.trg_audit()', t || '_audit', t);
  end loop;
end $$;
