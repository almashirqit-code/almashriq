-- =====================================================================
-- 0034: in-app notifications (the bell in the ERP and customer account)
--
--  * One row per recipient. Written only by the server (service key) at the
--    same moments as the email alerts (src/lib/notify.ts): sign-ups,
--    payment slips, inquiries, chat messages, approvals, invoices.
--  * Each user reads and marks read only their own rows; no direct writes.
--  * Published to Realtime so the bell updates live (read policy applies).
--  * Rows older than 90 days are removed whenever new ones are written.
-- Safe to re-run.
-- =====================================================================

create table if not exists public.notifications (
  id          bigint generated by default as identity primary key,
  user_id     uuid not null references auth.users (id) on delete cascade,
  kind        text not null,
  title       text not null,
  body        text,
  link        text,
  read_at     timestamptz,
  created_at  timestamptz not null default now()
);

do $$ begin
  alter table public.notifications add constraint notifications_values_chk check (
    char_length(kind) between 1 and 40
    and char_length(title) between 1 and 200
    and char_length(coalesce(body, '')) <= 500
    and (link is null or (link like '/%' and char_length(link) <= 300)));
exception when duplicate_object then null; end $$;

create index if not exists notifications_user_idx   on public.notifications (user_id, created_at desc);
create index if not exists notifications_unread_idx on public.notifications (user_id) where read_at is null;
create index if not exists notifications_age_idx    on public.notifications (created_at);

alter table public.notifications enable row level security;
drop policy if exists notifications_own on public.notifications;
create policy notifications_own on public.notifications for select to authenticated
  using (user_id = (select auth.uid()));

-- Mark the signed-in user's notifications read (all of them, or the given ids).
create or replace function public.mark_notifications_read(p_ids bigint[] default null)
returns void
language sql security definer set search_path = public
as $$
  update public.notifications
     set read_at = now()
   where user_id = auth.uid() and read_at is null
     and (p_ids is null or id = any (p_ids))
$$;
revoke all on function public.mark_notifications_read(bigint[]) from public, anon;
grant execute on function public.mark_notifications_read(bigint[]) to authenticated;

-- Housekeeping, called by the server after writing new rows.
create or replace function public.prune_notifications()
returns void
language sql security definer set search_path = public
as $$
  delete from public.notifications where created_at < now() - interval '90 days'
$$;
revoke all on function public.prune_notifications() from public, anon, authenticated;
grant execute on function public.prune_notifications() to service_role;

do $$ begin
  alter publication supabase_realtime add table public.notifications;
exception when duplicate_object then null; end $$;
