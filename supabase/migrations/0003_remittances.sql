-- ---------------------------------------------------------------------
-- Private storage bucket for TT documents (accessed with signed URLs)
-- ---------------------------------------------------------------------
insert into storage.buckets (id, name, public)
values ('remittance-docs', 'remittance-docs', false)
on conflict (id) do update set public = false;

drop policy if exists "remittance docs read" on storage.objects;
create policy "remittance docs read" on storage.objects for select to authenticated
  using (bucket_id = 'remittance-docs' and public.auth_role() is not null);

drop policy if exists "remittance docs insert" on storage.objects;
create policy "remittance docs insert" on storage.objects for insert to authenticated
  with check (bucket_id = 'remittance-docs' and public.is_staff(array['admin','manager']::public.user_role[]));

drop policy if exists "remittance docs delete" on storage.objects;
create policy "remittance docs delete" on storage.objects for delete to authenticated
  using (bucket_id = 'remittance-docs' and public.is_staff(array['admin','manager']::public.user_role[]));
