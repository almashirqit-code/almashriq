create policy rem_update on public.remittances for update to authenticated
  using (public.is_staff(array['admin','manager']::public.user_role[]))
  with check (public.is_staff(array['admin','manager']::public.user_role[]));
drop policy if exists rem_delete on public.remittances;
create policy rem_delete on public.remittances for delete to authenticated
  using (public.is_staff(array['admin']::public.user_role[]));

drop policy if exists remdoc_read on public.remittance_documents;
create policy remdoc_read on public.remittance_documents for select to authenticated using (public.auth_role() is not null);
drop policy if exists remdoc_write on public.remittance_documents;
create policy remdoc_write on public.remittance_documents for all to authenticated
  using (public.is_staff(array['admin','manager']::public.user_role[]))
  with check (public.is_staff(array['admin','manager']::public.user_role[]));

drop policy if exists remalloc_read on public.remittance_allocations;
create policy remalloc_read on public.remittance_allocations for select to authenticated using (public.auth_role() is not null);
drop policy if exists remalloc_write on public.remittance_allocations;
