-- Customers: numeric display ID + salesperson tag ("Tagged With")
alter table public.customers
  add column if not exists customer_no bigint generated by default as identity,
  add column if not exists assigned_to uuid references public.profiles (id) on delete set null;
create unique index if not exists customers_customer_no_uniq on public.customers (customer_no);

-- Offices and shift types used on remittances (edited in Configuration)
alter table public.settings
  add column if not exists offices text[] not null default array['Head Office'],
  add column if not exists shifts  text[] not null default array['Day', 'Night'];

-- ---------------------------------------------------------------------
-- Remittances
-- ---------------------------------------------------------------------
create table if not exists public.remittances (
  id                 bigint generated by default as identity primary key,
  customer_id        uuid not null references public.customers (id) on delete restrict,
  office             text not null,
  shift              text,
  currency           text not null check (currency in ('JPY', 'USD', 'EUR', 'GBP')),
  remitter           text not null,
  bank               text not null,
  bank_address       text not null,
  bank_phone         text,
  exchange_rate      numeric(14, 6) not null check (exchange_rate > 0),  -- 1 unit = N JPY
  instructed_amount  numeric(14, 2) not null check (instructed_amount > 0),
  remit_amount       numeric(14, 2) not null check (remit_amount > 0),
  bank_charges       numeric(14, 2) generated always as (instructed_amount - remit_amount) stored,
  remit_date         date not null,
  received_date      date not null,
  remarks            text,
  allocated_amount   numeric(14, 2) not null default 0,
  remaining_amount   numeric(14, 2) generated always as (remit_amount - allocated_amount) stored,
  status             text generated always as (
                       case when allocated_amount <= 0 then 'unallocated'
                            when allocated_amount < remit_amount then 'partial'
                            else 'allocated' end) stored,
  created_by         uuid references public.profiles (id) on delete set null,
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now(),
  constraint remittances_remit_lte_instructed check (remit_amount <= instructed_amount)
);
create index if not exists remittances_customer_idx on public.remittances (customer_id);
create index if not exists remittances_status_idx on public.remittances (status);
create index if not exists remittances_received_idx on public.remittances (received_date desc);

drop trigger if exists remittances_touch on public.remittances;
create trigger remittances_touch before update on public.remittances
  for each row execute function public.touch_updated_at();

-- TT copies and other documents (PDF or images), stored in a private bucket
create table if not exists public.remittance_documents (
  id             uuid primary key default gen_random_uuid(),
  remittance_id  bigint not null references public.remittances (id) on delete cascade,
  path           text not null,
  file_name      text not null,
  mime_type      text,
  size_bytes     bigint,
  created_by     uuid references public.profiles (id) on delete set null,
  created_at     timestamptz not null default now()
);
create index if not exists remittance_documents_rem_idx on public.remittance_documents (remittance_id);

-- Allocation of a remittance to stock (vehicles)
create table if not exists public.remittance_allocations (
  id             uuid primary key default gen_random_uuid(),
  remittance_id  bigint not null references public.remittances (id) on delete cascade,
  vehicle_id     uuid not null references public.vehicles (id) on delete restrict,
  amount         numeric(14, 2) not null check (amount > 0),   -- in the remittance currency
  created_by     uuid references public.profiles (id) on delete set null,
  created_at     timestamptz not null default now()
);
create index if not exists remittance_alloc_rem_idx on public.remittance_allocations (remittance_id);
create index if not exists remittance_alloc_vehicle_idx on public.remittance_allocations (vehicle_id);

-- Payments created from an allocation disappear with it
alter table public.payments
  add column if not exists allocation_id uuid references public.remittance_allocations (id) on delete cascade;

-- Keep allocated_amount in sync and never allow over-allocation
create or replace function public.trg_allocations_rollup()
returns trigger
language plpgsql security definer set search_path = public
as $$
declare
  rid bigint := coalesce(new.remittance_id, old.remittance_id);
  total numeric;
  cap numeric;
begin
  select coalesce(sum(amount), 0) into total from public.remittance_allocations where remittance_id = rid;
  select remit_amount into cap from public.remittances where id = rid;
  if total > cap + 0.005 then
    raise exception 'Allocation exceeds remittance amount (% > %)', total, cap using errcode = 'check_violation';
  end if;
  update public.remittances set allocated_amount = total where id = rid;
  return null;
end $$;

drop trigger if exists remittance_allocations_rollup on public.remittance_allocations;
create trigger remittance_allocations_rollup after insert or update or delete on public.remittance_allocations
  for each row execute function public.trg_allocations_rollup();

-- Lowering remit_amount below what's already allocated is not allowed
create or replace function public.trg_remittance_guard()
returns trigger language plpgsql as $$
begin
  if new.remit_amount < new.allocated_amount then
    raise exception 'Remit amount cannot be less than the amount already allocated (%)', new.allocated_amount
      using errcode = 'check_violation';
  end if;
  return new;
end $$;

drop trigger if exists remittances_guard on public.remittances;
create trigger remittances_guard before update on public.remittances
  for each row execute function public.trg_remittance_guard();

-- ---------------------------------------------------------------------
-- RLS: everyone signed in can view; admin/manager record and allocate;
-- only admin deletes remittances.
